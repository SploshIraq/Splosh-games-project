function normalizeWord(word) {
  return String(word || '')
    .toLocaleLowerCase('ar')
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .replace(/ـ/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/[ؤ]/g, 'و')
    .replace(/[ئ]/g, 'ي')
    .replace(/[ة]/g, 'ه')
    .replace(/[^\p{L}\p{N}]/gu, '')
    .replace(/^ال(?=.{2,})/u, '');
}

